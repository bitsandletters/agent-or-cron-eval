def generated() -> list[dict]:
    fixtures = []
    for anchor in ANCHORS:
        fixture = copy.deepcopy(anchor)
        rng = random.Random(fixture["seed"])
        for source in ("search_console", "posthog"):
            factor = rng.uniform(0.95, 1.05)
            position_shift = rng.uniform(-0.2, 0.2)
            for period in ("previous", "current"):
                for metric, value in fixture["sources"][source][period].items():
                    if value is not None:
                        fixture["sources"][source][period][metric] = (
                            round(value + position_shift, 3) if metric == "position"
                            else round(value * factor))
        fixtures.append(fixture)
    return fixtures


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if committed fixtures differ")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    errors = []
    for fixture in generated():
        path = root / fixture["split"] / (fixture["fixture_id"] + ".json")
        content = json.dumps(fixture, indent=2, allow_nan=False) + "\n"
        if args.check:
            if not path.exists() or path.read_text() != content:
                errors.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if errors:
        print("Fixture reproducibility failed: " + ", ".join(errors))
        return 1
    print(f"{'Verified' if args.check else 'Generated'} {len(ANCHORS)} seeded synthetic fixtures")
    return 0


